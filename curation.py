def refine_cat(name, cat):
    for w in KID_WORDS:
        if w in name:
            return "儿童"
    return cat if cat in ALLOW_GROUPS else ""

# 允许的分类（游戏类整体不放行：TV 游戏几乎全是灰产/山寨）
ALLOW_GROUPS = {"影音", "工具", "生活"}


def _hit_black(name):
    for b in BLACK:
        if b in name:
            return b
    return None


def is_safe(name, cat=""):
    """返回 (是否放行, 原因)"""
    if not name:
        return False, "空名称"
    name = name.strip()

    b = _hit_black(name)
    if b:
        return False, "黑名单:%s" % b

    if cat and cat not in ALLOW_GROUPS:
        return False, "分类不收:%s" % cat

    for e in SAFE_EXACT:
        if e == name:
            return True, "精确白名单"

    for s in SAFE_BRANDS:
        if s in name:
            return True, "品牌:%s" % s

    return False, "不在白名单"


